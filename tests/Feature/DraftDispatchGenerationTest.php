<?php

declare(strict_types=1);

use Illuminate\Contracts\Events\ShouldDispatchAfterCommit;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Event;
use Storix\Actions\CreateDispatchAction;
use Storix\Data\CreateDispatchData;
use Storix\Events\GenerateDraftDispatchRequested;
use Storix\Listeners\GenerateDraftDispatch;
use Storix\Models\Container;
use Storix\Models\Dispatch;
use Storix\Models\DispatchEntry;
use Storix\Tests\Fixtures\Models\DeliveryNote;
use Storix\Tests\Fixtures\Models\User;

it('encapsulates an immutable draft generation request that dispatches after commit', function (): void {
    $data = new CreateDispatchData(
        deliveryNoteId: 10,
        dispatchedBy: 20,
        quantity: 2,
        customerId: 15,
        dispatchedAt: '2026-07-20 09:00:00',
        dispatchNote: 'Generated by a host workflow',
        containerIds: [30, 40],
        idempotencyKey: 'delivery-note:10:draft-dispatch',
        metadata: ['source' => 'delivery-note-approved'],
    );

    $event = new GenerateDraftDispatchRequested($data);

    expect($event)->toBeInstanceOf(ShouldDispatchAfterCommit::class)
        ->and($event->data)->toBe($data)
        ->and($event->data->deliveryNoteId)->toBe(10)
        ->and($event->data->quantity)->toBe(2)
        ->and($event->data->containerIds)->toBe([30, 40])
        ->and($event->data->metadata)->toBe(['source' => 'delivery-note-approved']);
});

it('registers the draft generation listener with the package event dispatcher', function (): void {
    Event::fake();

    Event::assertListening(
        GenerateDraftDispatchRequested::class,
        GenerateDraftDispatch::class,
    );
});

it('generates a draft dispatch with reservations and audit context', function (): void {
    $user = User::query()->create(['name' => 'Event Dispatcher', 'email' => 'event-dispatch@example.com']);
    $deliveryNote = DeliveryNote::query()->create(['name' => 'Event delivery']);
    $container = Container::factory()->create();

    GenerateDraftDispatchRequested::dispatch(new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 1,
        customerId: $deliveryNote->customer_id,
        dispatchedAt: '2026-07-20 09:30:00',
        dispatchNote: 'Created from delivery note approval',
        containerIds: [$container->id],
        idempotencyKey: 'delivery-note:event-delivery:draft-dispatch',
        metadata: [
            'source' => 'delivery-note-approved',
            'correlation_id' => 'correlation-1001',
        ],
    ));

    $dispatch = Dispatch::query()
        ->where('idempotency_key', 'delivery-note:event-delivery:draft-dispatch')
        ->firstOrFail();

    expect((string) $dispatch->state)->toBe('draft')
        ->and($dispatch->delivery_note_id)->toBe($deliveryNote->id)
        ->and($dispatch->dispatched_by)->toBe($user->id)
        ->and($dispatch->dispatched_at?->toDateTimeString())->toBe('2026-07-20 09:30:00')
        ->and($dispatch->dispatch_note)->toBe('Created from delivery note approval')
        ->and($dispatch->metadata)->toBe([
            'source' => 'delivery-note-approved',
            'correlation_id' => 'correlation-1001',
        ])
        ->and($dispatch->entries)->toHaveCount(1)
        ->and($dispatch->entries->first()?->container_id)->toBe($container->id)
        ->and(Container::query()->availableForDispatch()->pluck('id'))->not->toContain($container->id);
});

it('defers generation until the surrounding transaction commits', function (): void {
    $user = User::query()->create(['name' => 'Commit Dispatcher', 'email' => 'commit@example.com']);
    $deliveryNote = DeliveryNote::query()->create(['name' => 'Committed delivery']);
    $startingTransactionLevel = DB::transactionLevel();

    DB::beginTransaction();

    try {
        GenerateDraftDispatchRequested::dispatch(new CreateDispatchData(
            deliveryNoteId: $deliveryNote->id,
            dispatchedBy: $user->id,
            quantity: 1,
            customerId: $deliveryNote->customer_id,
            idempotencyKey: 'delivery-note:commit:draft-dispatch',
        ));

        expect(Dispatch::query()->where('idempotency_key', 'delivery-note:commit:draft-dispatch')->exists())
            ->toBeFalse();

        DB::commit();
    } finally {
        while (DB::transactionLevel() > $startingTransactionLevel) {
            DB::rollBack();
        }
    }

    expect(Dispatch::query()->where('idempotency_key', 'delivery-note:commit:draft-dispatch')->exists())
        ->toBeTrue();
});

it('discards generation when the surrounding transaction rolls back', function (): void {
    $user = User::query()->create(['name' => 'Rollback Dispatcher', 'email' => 'rollback@example.com']);
    $deliveryNote = DeliveryNote::query()->create(['name' => 'Rolled back delivery']);
    $startingTransactionLevel = DB::transactionLevel();

