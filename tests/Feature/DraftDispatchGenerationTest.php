    expect(Dispatch::query()->where('idempotency_key', 'delivery-note:rollback:draft-dispatch')->exists())
        ->toBeFalse();
});

it('handles equivalent retries without creating duplicate dispatches or reservations', function (): void {
    $user = User::query()->create(['name' => 'Retry Dispatcher', 'email' => 'retry@example.com']);
    $deliveryNote = DeliveryNote::query()->create(['name' => 'Retry delivery']);
    $firstContainer = Container::factory()->create();
    $secondContainer = Container::factory()->create();

    $firstRequest = new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 2,
        customerId: $deliveryNote->customer_id,
        dispatchedAt: '2026-07-20 10:00:00',
        dispatchNote: 'Retry-safe request',
        containerIds: [$secondContainer->id, $firstContainer->id],
        idempotencyKey: 'delivery-note:retry:draft-dispatch',
        metadata: [
            'source' => 'queued-job',
            'context' => ['sequence' => 10, 'tenant' => 'central'],
        ],
    );
    $equivalentRetry = new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 2,
        customerId: $deliveryNote->customer_id,
        dispatchedAt: '2026-07-20 10:00:00',
        dispatchNote: 'Retry-safe request',
        containerIds: [$firstContainer->id, $secondContainer->id],
        idempotencyKey: 'delivery-note:retry:draft-dispatch',
        metadata: [
            'context' => ['tenant' => 'central', 'sequence' => 10],
            'source' => 'queued-job',
        ],
    );

    GenerateDraftDispatchRequested::dispatch($firstRequest);
    GenerateDraftDispatchRequested::dispatch($equivalentRetry);

    $dispatch = Dispatch::query()
        ->where('idempotency_key', 'delivery-note:retry:draft-dispatch')
        ->firstOrFail();

    expect(Dispatch::query()->count())->toBe(1)
        ->and($dispatch->idempotency_fingerprint)->toMatch('/^[a-f0-9]{64}$/')
        ->and($dispatch->entries)->toHaveCount(2)
        ->and(DispatchEntry::query()->count())->toBe(2);
});

it('rejects conflicting reuse of an idempotency key', function (): void {
    $user = User::query()->create(['name' => 'Conflict Dispatcher', 'email' => 'conflict@example.com']);
    $deliveryNote = DeliveryNote::query()->create(['name' => 'Conflict delivery']);

    GenerateDraftDispatchRequested::dispatch(new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 1,
        customerId: $deliveryNote->customer_id,
        dispatchedAt: '2026-07-20 10:30:00',
        dispatchNote: 'Original request',
        idempotencyKey: 'delivery-note:conflict:draft-dispatch',
    ));

    expect(fn () => GenerateDraftDispatchRequested::dispatch(new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 1,
        customerId: $deliveryNote->customer_id,
        dispatchedAt: '2026-07-20 10:30:00',
        dispatchNote: 'Conflicting request',
        idempotencyKey: 'delivery-note:conflict:draft-dispatch',
    )))->toThrow(
        DomainException::class,
        'The dispatch idempotency key [delivery-note:conflict:draft-dispatch] has already been used for another request.',
    );

    expect(Dispatch::query()->count())->toBe(1);
});

it('treats a quantity change as conflicting idempotent input', function (): void {
    $user = User::query()->create(['name' => 'Quantity Dispatcher', 'email' => 'quantity-conflict@example.com']);
    $deliveryNote = DeliveryNote::query()->create(['name' => 'Quantity conflict delivery']);

    GenerateDraftDispatchRequested::dispatch(new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 4,
        customerId: $deliveryNote->customer_id,
        idempotencyKey: 'delivery-note:quantity-conflict:draft-dispatch',
    ));

    expect(fn () => GenerateDraftDispatchRequested::dispatch(new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 5,
        customerId: $deliveryNote->customer_id,
        idempotencyKey: 'delivery-note:quantity-conflict:draft-dispatch',
    )))->toThrow(
        DomainException::class,
        'The dispatch idempotency key [delivery-note:quantity-conflict:draft-dispatch] has already been used for another request.',
    );

    expect(Dispatch::query()->sole()->quantity)->toBe(4);
});

it('rolls back the complete draft when reservation validation fails', function (): void {
    $user = User::query()->create(['name' => 'Invalid Dispatcher', 'email' => 'invalid@example.com']);
    $deliveryNote = DeliveryNote::query()->create(['name' => 'Invalid delivery']);
    $container = Container::factory()->create(['is_active' => false]);

    expect(fn () => GenerateDraftDispatchRequested::dispatch(new CreateDispatchData(
        deliveryNoteId: $deliveryNote->id,
        dispatchedBy: $user->id,
        quantity: 1,
        customerId: $deliveryNote->customer_id,
        containerIds: [$container->id],
        idempotencyKey: 'delivery-note:invalid:draft-dispatch',
    )))->toThrow(DomainException::class, "Container [{$container->serial}] is inactive.");

    expect(Dispatch::withTrashed()->where('idempotency_key', 'delivery-note:invalid:draft-dispatch')->exists())
        ->toBeFalse()
        ->and(DispatchEntry::withTrashed()->exists())->toBeFalse();
});

